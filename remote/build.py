"""
Build a self-contained Kaggle notebook that runs a named batch of discsim
simulations on Kaggle's free CPU notebooks.

The notebook carries the working tree's ``discsim`` package and ``scripts/`` as
%%writefile cells, so a run uses exactly the local code: nothing needs to be
committed or pushed first. Kaggle's image already has numpy, scipy and
matplotlib, so the notebook needs no internet access.

Each notebook writes the code into /tmp/discsim, runs the batch's commands in
turn from there (each logged, carrying on past a failure) with outputs in
/kaggle/working/outputs, and tars them into /kaggle/working/outputs.tar.gz.

Usage (from the repository root, after `poetry install --with remote` and a
Kaggle API token in ~/.kaggle/):
    poetry run python remote/build.py test
    poetry run kaggle kernels push -p remote/build/test
or let remote/runs.py do the pushing, waiting and downloading.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CODE = sorted(p.relative_to(ROOT).as_posix() for p in [*(ROOT / "discsim").glob("*.py"),
                                                       *(ROOT / "scripts").glob("*.py")])

# Batch name -> commands, run from the code's root with outputs/ pointing at
# /kaggle/working/outputs. A Kaggle CPU session has 4 cores, 30 GB and 12 hours;
# the SPH is single-threaded, so one long simulation per batch, several batches
# at once (up to 5 sessions).
BATCHES = {
    # smoke test, ~2 minutes: the pipeline end to end on a tiny disc
    "test": ["python scripts/embedded_body.py --n 3000 --orbits 0.3 --out outputs/test"],
    # E2: embedded body vs none at higher resolution and for longer (each runs a q = 0 twin); lags averaged
    # over 10 snapshots in the last orbit, which are kept for reprocessing (e.g. other lamppost heights)
    **{f"e2_q{tag}": [f"python scripts/embedded_body.py --n 30000 --orbits 8 --q {q} --avg-orbits 1 "
                      f"--avg-snaps 10 --out outputs/e2_q{tag}"]
       for tag, q in [("1e-3", 1e-3), ("5e-3", 5e-3), ("1e-2", 1e-2)]},
    # the README animation at higher resolution
    "anim_hires": ["python scripts/animate_disc.py --n 30000 --orbits 4 --frames 120 --out outputs/anim_hires "
                   "--gif outputs/anim_hires/disc_animation.gif"],
}


def _cell(source: str, kind: str = "code") -> dict:
    cell = {"cell_type": kind, "metadata": {}, "source": source.splitlines(keepends=True)}
    if kind == "code":
        cell.update(execution_count=None, outputs=[])
    return cell


def git_state() -> str:
    sha = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    dirty = subprocess.run(["git", "diff", "--quiet", "HEAD"], cwd=ROOT).returncode != 0
    return sha + ("+local changes" if dirty else "")


def build(batch: str, username: str, out_dir: Path) -> Path:
    commands = BATCHES[batch]
    cells = [_cell(
        f"# discsim batch `{batch}`\n\nGenerated by `remote/build.py` from discsim `{git_state()}`. Runs:\n\n"
        + "\n".join(f"- `{c}`" for c in commands)
        + "\n\nOutput: `outputs/` (logs in `outputs/logs/`) and `outputs.tar.gz`.", "markdown")]
    cells.append(_cell(
        "%%bash\nmkdir -p /tmp/discsim/discsim /tmp/discsim/scripts /kaggle/working/outputs/logs\n"
        "ln -sfn /kaggle/working/outputs /tmp/discsim/outputs\n"
        "(lscpu | grep -E 'Model name|^CPU\\(s\\)'; free -g | head -2; which ffmpeg) "
        "> /kaggle/working/outputs/logs/machine.txt 2>&1\n"
        "python -c 'import numpy, scipy, matplotlib, os; "
        "print(\"numpy\", numpy.__version__, \"scipy\", scipy.__version__, \"cpus\", os.cpu_count())'\n"))
    for rel in CODE:
        cells.append(_cell(f"%%writefile /tmp/discsim/{rel}\n" + (ROOT / rel).read_text()))
    cells.append(_cell(
        "import os, subprocess, time\n"
        "os.environ['MPLBACKEND'] = 'Agg'\n"
        "os.environ['PYTHONPATH'] = '/tmp/discsim'\n"
        f"COMMANDS = {json.dumps(commands, indent=1)}\n"
        "failed = []\n"
        "for i, cmd in enumerate(COMMANDS):\n"
        "    t0 = time.time()\n"
        "    with open(f'/kaggle/working/outputs/logs/{i:02d}.log', 'w') as log:\n"
        "        log.write(cmd + '\\n')\n"
        "        log.flush()\n"
        "        rc = subprocess.call(cmd, shell=True, cwd='/tmp/discsim', stdout=log, stderr=subprocess.STDOUT)\n"
        "    print(f'[{rc}] {time.time() - t0:7.0f}s  {cmd}', flush=True)\n"
        "    if rc:\n"
        "        failed.append(cmd)\n"
        "print('FAILED:', failed if failed else 'none')\n"))
    cells.append(_cell("%%bash\ncd /kaggle/working && tar czf outputs.tar.gz outputs && ls -la "
                       "&& tail -n 5 outputs/logs/*.log\n"))
    for i, c in enumerate(cells):
        c["id"] = f"cell{i:02d}"
    nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                                       "name": "python3"},
                                        "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 5}
    out = out_dir / batch
    out.mkdir(parents=True, exist_ok=True)
    (out / "notebook.ipynb").write_text(json.dumps(nb, indent=1))
    slug = "discsim-" + batch.replace("_", "-").replace(".", "-").lower()
    meta = {"id": f"{username}/{slug}", "title": slug, "code_file": "notebook.ipynb", "language": "python",
            "kernel_type": "notebook", "is_private": True, "enable_gpu": False, "enable_tpu": False,
            "enable_internet": False, "dataset_sources": [], "competition_sources": [], "kernel_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    return out


def kaggle_username() -> str:
    # Works with either kaggle.json or an access token (~/.kaggle/access_token).
    config = subprocess.check_output(["kaggle", "config", "view"], text=True)
    return next(line.split(":", 1)[1].strip() for line in config.splitlines()
                if line.strip().startswith("- username:"))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("batches", nargs="+", choices=sorted(BATCHES))
    parser.add_argument("--username", help="Kaggle username (default: the CLI's)")
    args = parser.parse_args()
    username = args.username or kaggle_username()
    for batch in args.batches:
        print(build(batch, username, HERE / "build"))


if __name__ == "__main__":
    main()
